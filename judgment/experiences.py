def _cosine_sim(a: List[float], b: List[float]) -> float:
    """缂傚倸鍊搁崐鐑芥倿閿曞倸绠�婵犻潧锟斤拷缁狅拷闂佽法鍣﹂幏锟� Python cosine similarity闂傚倸鍊烽悞锔撅拷绗涘懐鐭欓柟杈鹃檮閸嬪��鈹戦悩韫�杩规繛鎴欏灪閺呮悂鏌ㄩ悤鍌涘�� numpy 濠电姷鏁搁崑鐐哄箰閼姐倕鏋堢�广儱娲﹀畷鏌ユ煕閳╁啰鎳呴柣锟芥径鎰�鐓曢柍鈺佸暟閳�鏇㈡煛閸滃啯瀚规繝鐢靛О閸ㄧ厧鈻斿☉銏″亱闁绘劕鎼�缁狅拷闂佺粯鍨兼慨銈夊疾閹间焦鐓ラ柣鏇炲�圭�氾拷"""
    dot = sum(x * y for x, y in zip(a, b))
    norm_a = math.sqrt(sum(x * x for x in a))
    norm_b = math.sqrt(sum(x * x for x in b))
    if norm_a == 0 or norm_b == 0:
        return 0.0
    return dot / (norm_a * norm_b)


